"""Import of Follow the Money entities (Aleph, OpenSanctions, ftm CLI).

Reads a file of FtM entities - JSON lines (one entity per line), a JSON
array, or {"entities": [...]} - and turns it into the TABLE that the guided
import already understands (nome1, tipo1, collegamento, nome2, tipo2 + columns):
so the file goes through the same three steps (columns, preview, import)
as a CSV, without a separate procedure.

    edge schemas (Ownership, Directorship, Family, Payment...)
        -> one row per edge: the two nodes and the link with the label
           of the edge and its properties ("owns (percentage 60)")
    entity-type properties (Passport.holder, Sanction.entity...)
        -> one row per link, with the name of the property
    remaining entities  -> one row with node 1 only
    schemas with a native type (generated/ontology_ftm.py: sanction, license...)
        -> native type + 'campi' column (JSON) with the scalar properties
    other scalar properties -> free columns, which become fields of the card

The FtM schema lives in generated/ftm_schema.json (generated by scripts/ftm/make_ftm_types.py):
no dependency on the followthemoney package at runtime."""
